// Builds the two copy-paste files in dist/:
//   dist/index.html  one self-contained page (CSS + JS inlined)
//   dist/worker.js   one Worker that serves that page and answers /api/barry
//                    via Workers AI, for pasting into the Cloudflare dashboard.
// Run: npm run bundle
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

let html = read("public/index.html");
const inline = (tag, file) => `<${tag}>\n${read("public/" + file)}\n</${tag}>`;
html = html.replace('<link rel="stylesheet" href="style.css">', () => inline("style", "style.css"));
html = html.replace('<script src="barry.js"></script>', () => inline("script", "barry.js"));
html = html.replace('<script src="terminal.js"></script>', () => inline("script", "terminal.js"));
if (/src="(barry|terminal)\.js"|href="style\.css"/.test(html)) throw new Error("inlining failed");

// Worker: src/index.js with the page embedded. Named exports become plain
// declarations (the dashboard editor wants a single default export).
let worker = read("src/index.js")
  .replace(/^export (const|function|class) /gm, "$1 ")
  .replace(
    "    // Anything else that reached the Worker: hand to static assets.\n    return env.ASSETS.fetch(request);",
    '    if (url.pathname === "/" || url.pathname === "/index.html") {\n' +
    '      return new Response(PAGE, { headers: { "content-type": "text/html; charset=utf-8" } });\n' +
    "    }\n" +
    '    return new Response("Not found", { status: 404 });'
  );
if (worker.includes("env.ASSETS")) throw new Error("asset fallback not replaced");

const header =
  "// Barry: single-file Cloudflare Worker. Generated by scripts/bundle.mjs, do not edit by hand.\n" +
  "// Dashboard setup: Settings > Bindings > Add > Workers AI, variable name AI.\n" +
  "// Optional variables: BARRY_MODEL, BARRY_MAX_TOKENS.\n\n";
worker = header + "const PAGE = " + JSON.stringify(html) + ";\n\n" + worker;

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist/index.html"), html);
writeFileSync(join(root, "dist/worker.js"), worker);
console.log(`dist/index.html ${html.length} bytes, dist/worker.js ${worker.length} bytes`);
